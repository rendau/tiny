package linktag

import "context"

// Keeper ведёт справочник меток — список меток, которые встречаются у ссылок (его показывает
// админка в фильтре и подсказках).
//
// Работает в фоне и отдельно от записи ссылок: тот, кто записал ссылку, только сообщает об этом
// через Changed и идёт дальше. Сбой или задержка справочника на создание и открытие ссылок не
// влияют; что при этом потерялось, исправляет редкий пересчёт перебором таблицы ссылок.
type Keeper interface {
	// Start запускает фоновую работу: обработку сообщений Changed и пересчёт (первый — вскоре
	// после запуска, дальше — раз в сутки). Останавливается отменой ctx.
	Start(ctx context.Context)
	// Wait ждёт, пока фоновая работа закончится
	Wait()

	// Changed сообщает, что ссылку записали: метки added у неё появились, removed — пропали.
	// Не ждёт и ошибок не возвращает: в базу ходит фоновая работа.
	Changed(added, removed []string)
}
