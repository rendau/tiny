package constant

import "time"

const (
	// QueueSize — сколько сообщений об изменённых метках может ждать обработки. Очередь полна —
	// сообщение отбрасывается (запись ссылки ждать не должна), его восполнит пересчёт.
	QueueSize = 1024

	// EventTimeout — сколько даётся одному обращению к справочнику
	EventTimeout = 10 * time.Second

	// RecountFirstDelay — через сколько после запуска идёт первый пересчёт. Не сразу: при выкладке
	// прежние копии сервиса ещё создают ссылки, не сообщая о метках, — пересчёт должен прийти
	// после них.
	RecountFirstDelay = 10 * time.Minute

	// RecountInterval — как часто пересчитывать дальше. Пересчёт читает всю таблицу ссылок, чаще
	// незачем.
	RecountInterval = 24 * time.Hour

	// RecountTimeout — сколько даётся одному пересчёту
	RecountTimeout = 10 * time.Minute
)
