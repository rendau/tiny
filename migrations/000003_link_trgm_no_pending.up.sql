-- Индексы поиска по части адреса и названия — без очереди отложенных записей (fastupdate).
--
-- С очередью новая ссылка попадает в индекс не сразу, а в список ожидания; когда список дорастает
-- до 4 МБ (около 2000 ссылок, то есть раз в сутки), его целиком разбирает одна вставка — та, на
-- которой он переполнился. Разбор трогает десятки тысяч страниц индекса: на 1,8 млн ссылок это
-- ~90 МБ чтения и ~50 МБ записи, на медленном диске — минуты. Клиент столько не ждёт и обрывает
-- запрос, следующая вставка начинает разбор заново, и создание ссылок не работает, пока список не
-- разобран (так было в бою: 8 минут ошибок 500 на каждое создание).
--
-- Без очереди каждая вставка сама вносит свои 100–350 страниц индекса: миллисекунды, пока они в
-- памяти, до секунды с холодного диска — и никаких провалов.
--
-- То, что уже лежит в списке ожидания, остаётся там до ближайшей очистки таблицы (vacuum) — поиску
-- это не мешает. Разбирать список прямо здесь нельзя: это та самая тяжёлая операция.
alter index link_long_url_trgm_idx set (fastupdate = off);
alter index link_title_trgm_idx set (fastupdate = off);
