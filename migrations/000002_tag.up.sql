-- справочник меток: какие метки встречаются у ссылок. Нужен, чтобы список меток (фильтр и
-- подсказки в админке) не собирать чтением всей таблицы link: на 1,76 млн ссылок это 0,7 ГБ и
-- секунды на каждый запрос, а из справочника — доли миллисекунды.
--
-- Справочник ведёт код сервиса, триггеров нет (internal/service/linktag): после записи ссылки её
-- метки дописываются сюда в фоне. С записью самой ссылки это не связано — ни общей транзакции, ни
-- ожидания: сбой справочника на создание и открытие ссылок не влияет. Что при этом потерялось или
-- устарело, исправляет редкий пересчёт перебором таблицы link.
create table tag (
    name text primary key
);

-- по уже существующим ссылкам
insert into tag (name)
select distinct unnest(tags)
from link;
